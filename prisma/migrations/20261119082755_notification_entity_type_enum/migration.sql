-- Convert existing notification entity types to the shared ActivityModule enum.
-- Unknown legacy values are retained as OTHER so the migration does not discard rows.
ALTER TABLE "notifications"
ALTER COLUMN "entityType" TYPE "ActivityModule"
USING (
  CASE UPPER("entityType")
    WHEN 'AUTH' THEN 'AUTH'
    WHEN 'USER' THEN 'USER'
    WHEN 'ROLE' THEN 'ROLE'
    WHEN 'PERMISSION' THEN 'PERMISSION'
    WHEN 'PRODUCT' THEN 'PRODUCT'
    WHEN 'PRODUCTVARIANT' THEN 'PRODUCT'
    WHEN 'PRODUCTOPTION' THEN 'PRODUCT'
    WHEN 'SIZEGUIDE' THEN 'PRODUCT'
    WHEN 'CATEGORY' THEN 'CATEGORY'
    WHEN 'BRAND' THEN 'BRAND'
    WHEN 'SUPPLIER' THEN 'SUPPLIER'
    WHEN 'WAREHOUSE' THEN 'WAREHOUSE'
    WHEN 'INVENTORY' THEN 'INVENTORY'
    WHEN 'STOCK' THEN 'INVENTORY'
    WHEN 'STOCK_MOVEMENT' THEN 'STOCK_MOVEMENT'
    WHEN 'STOCK_TRANSFER' THEN 'STOCK_TRANSFER'
    WHEN 'PURCHASE' THEN 'PURCHASE'
    WHEN 'CUSTOMER' THEN 'CUSTOMER'
    WHEN 'CART' THEN 'CART'
    WHEN 'ORDER' THEN 'ORDER'
    WHEN 'PAYMENT' THEN 'PAYMENT'
    WHEN 'ORDER_RETURN' THEN 'ORDER_RETURN'
    WHEN 'PURCHASE_RETURN' THEN 'PURCHASE_RETURN'
    WHEN 'EMPLOYEE' THEN 'EMPLOYEE'
    WHEN 'SETTINGS' THEN 'SETTINGS'
    WHEN 'NOTIFICATION' THEN 'NOTIFICATION'
    WHEN 'OTHER' THEN 'OTHER'
    ELSE 'OTHER'
  END
)::"ActivityModule";
